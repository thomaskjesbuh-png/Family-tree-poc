"""Parse Digitalarkivet census booklets (1865, 1900, 1910) into Records.

The booklets are PDFs generated by Digitalarkivet with the full transcription
of one municipality: dwellings, then each person with name, sex, marital status,
family role, occupation, age or birth date, and birthplace. We read them with
`pdftotext -layout` (poppler-utils) and parse line by line.

Column positions shift when a long name overflows, so each person line is
parsed with patterns (sex + marital code after the name, then the age/date/year,
then the birthplace). Header column positions are used only to tell family role
from occupation and to attach wrapped name lines.
"""

from __future__ import annotations

import re
import subprocess
from dataclasses import dataclass
from pathlib import Path

from ..models import Record
from .. import names
from .households import Member, assign_relations

BOOKLET_BASE = "https://xml.arkivverket.no/folketellinger/hefter"
COUNTY_NAME = {"01Ostfold": "Østfold"}

_PERSON = re.compile(r"^(\d{3}) (.+)$")
_SEX = re.compile(r"\s(m|k)\*?(?=\s)")
_MARITAL = {"ug", "g", "e", "s", "f", "sk", "gj", "sep", "?", "-"}
_AGE = re.compile(r"(\d{1,3})(?:/\d+)?\s*\(alder\)")
_DATE_OR_YEAR = re.compile(r"(\d{2}\.\d{2}\.(\d{4})|\b(1[6-9]\d\d)\b|\b(\d{2})\.\d{2}\.\d{2}\b)")
_SKIP_LINE = re.compile(
    r"^\s*(Side \d+|Folketeljinga \d{4}\s*$|Personar i alt|Ny teljingskrins|Ny tellingskrets|"
    r"Digitalarkivet - Arkivverket|Merknad|Sannsynleg|Sedvanleg|Eigar:|Utsæd|Kjøk\.|Sidebygn|NB/)")
_REGISTER = re.compile(r"^\s*(Førenamnsregister|Etternamnsregister|Fødestadregister|Bustadsregister)\s*$")
_PRGJ = re.compile(r"Prestegjeld:\s*(.+?)(?=\s+Herred/by:|\s*$)")
_HERRED = re.compile(r"Herred/by:\s*(.+?)\s*$")
_BOST_CODES = {"b", "f", "mt", "bt", "fb", "tb", "bf"}
_DITTO = {"do", "do.", "ditto", "dito", "ds", "ds."}


@dataclass
class _Cols:
    sex: int
    fam: int
    yrkje: int
    fodd: int
    fodested: int
    has_bust: bool


@dataclass
class _Person:
    name: str
    sex: str
    marital: str
    role: str
    occupation: str
    born: str
    birthplace: str
    page: int
    dwelling: str


def pdf_to_pages(pdf: Path) -> list[str]:
    out = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], check=True,
                         capture_output=True).stdout.decode("utf-8", errors="replace")
    return out.split("\f")


def _header_cols(line: str) -> _Cols:
    def pos(label: str, default: int) -> int:
        i = line.find(label)
        return i if i >= 0 else default
    return _Cols(sex=pos("Kj.", 34), fam=pos("Fam.", 40), yrkje=pos("Yrkje", 60),
                 fodd=pos("Fødd", 90), fodested=pos("Fødestad", 100), has_bust="Bust." in line)


def _chunks(text: str, offset: int) -> list[tuple[int, str]]:
    """Split on runs of 2+ spaces, keeping absolute start positions."""
    return [(offset + m.start(), m.group(0).strip()) for m in re.finditer(r"\S+(?: \S+)*", text)]


def _parse_person(line: str, cols: _Cols, year: int, page: int, dwelling: str) -> _Person | None:
    m = _PERSON.match(line)
    if not m:
        return None
    # sex is the standalone m/k nearest the "Kj." column; a marital code may follow
    sexes = [h for h in _SEX.finditer(line, 5) if abs(h.start() - cols.sex) <= 14]
    if not sexes:
        return None
    sx = min(sexes, key=lambda h: abs(h.start() - cols.sex))
    name = line[4:sx.start()].strip().replace("*", "").strip()
    if not name:
        return None
    rest_start = sx.end()
    marital = ""
    mm = re.match(r"\s+(\S+)", line[rest_start:])
    if mm and mm.group(1).rstrip("*") in _MARITAL:
        marital = mm.group(1).rstrip("*")
        rest_start += mm.end()

    pat = _AGE if year == 1865 else _DATE_OR_YEAR
    hits = list(pat.finditer(line, rest_start))
    if not hits:
        born_m = None
        middle_end = len(line)
    else:
        born_m = min(hits, key=lambda h: abs(h.start() - cols.fodd))
        middle_end = born_m.start()
    middle = line[rest_start:middle_end]

    role, occupation = "", ""
    chunks = _chunks(middle, rest_start)
    if cols.has_bust and chunks:
        first_pos, first = chunks[0]
        toks = first.split()
        if toks and toks[0] in _BOST_CODES:
            toks = toks[1:]
        if toks:
            role = toks[0]
            rest = " ".join(toks[1:])
            occupation = " ".join([rest] + [c for _, c in chunks[1:]]).strip()
        elif len(chunks) > 1 and chunks[1][0] < cols.yrkje - 1:
            role = chunks[1][1]
            occupation = " ".join(c for _, c in chunks[2:])
        else:
            occupation = " ".join(c for _, c in chunks[1:])
    else:
        for p, c in chunks:
            if p < cols.yrkje - 1 and not role:
                role = c
            else:
                occupation = (occupation + " " + c).strip()

    born, birthplace = "", ""
    if born_m:
        born = born_m.group(0)
        after = line[born_m.end():]
        bp = _chunks(after, 0)
        birthplace = bp[0][1] if bp else ""
        if cols.has_bust:
            # citizenship / religion codes ("n", "s") can run into the birthplace
            birthplace = re.sub(r"(\s+[a-z?]{1,2})+$", "", birthplace).strip()
    return _Person(name=name, sex="m" if sx.group(1) == "m" else "f", marital=marital,
                   role=role, occupation=occupation, born=born, birthplace=birthplace,
                   page=page, dwelling=dwelling)


def _birth_year(born: str, year: int) -> tuple[int | None, bool]:
    if not born:
        return None, False
    a = _AGE.match(born)
    if a:
        # 1865 count date was 31 Dec 1865, so census year minus age.
        return year - int(a.group(1)), True
    d = _DATE_OR_YEAR.search(born)
    if d:
        if d.group(2) or d.group(3):
            return int(d.group(2) or d.group(3)), False
        yy = int(d.group(4))  # yy.mm.dd, e.g. "81.11.27" in 1900
        century = 1800 if yy > year % 100 else 1900
        return century + yy, False
    return None, False


def split_name(full: str) -> tuple[str, str]:
    """Given names vs patronymic/surname: the surname starts at the first
    patronymic after the first token, else it is the last token."""
    toks = full.split()
    if len(toks) <= 1:
        return full, ""
    for i in range(1, len(toks)):
        if names.patronymic_root(toks[i]):
            return " ".join(toks[:i]), " ".join(toks[i:])
    return " ".join(toks[:-1]), toks[-1]


def _drop_inconsistent_fathers(members: list[Member]) -> None:
    """Drop an inferred father whose name can't fit the child's surname.

    A child coded "d"/"s" whose patronymic points to another father (Karola
    Pettersen in Arnt Andersen's household) is a stepchild or servant.
    """
    for m in members:
        father = m.relations.get("father")
        if not father:
            continue
        _, child_sur = split_name(m.name)
        _, father_sur = split_name(father)
        if not child_sur or names.clean(child_sur) == names.clean(father_sur):
            continue
        roots = names.father_patronymic_roots(father)
        child_roots = {pr[0] for t in names.clean(child_sur).split() if (pr := names.patronymic_root(t))}
        if child_roots and not (child_roots & roots):
            del m.relations["father"]


def parse_booklet(pdf: Path, year: int, county_dir: str = "01Ostfold") -> list[Record]:
    pages = pdf_to_pages(pdf)
    muni_code = re.search(r"(\d{4})_hefte", pdf.name)
    muni_code = muni_code.group(1) if muni_code else "????"
    muni_name = ""      # herred/by (municipality)
    parish_name = ""    # prestegjeld (church parish), when given
    county = COUNTY_NAME.get(county_dir, "")

    groups: list[list[_Person]] = []
    current: list[_Person] = []
    cols: _Cols | None = None
    dwelling = ""
    pending_dwelling_header: str | None = None
    seen_person = False
    last: _Person | None = None
    stop = False

    def flush():
        nonlocal current
        if current:
            groups.append(current)
        current = []

    for pageno, text in enumerate(pages, 1):
        if stop:
            break
        for line in text.splitlines():
            if not line.strip():
                continue
            if seen_person and _REGISTER.match(line):
                stop = True
                break
            if line.lstrip().startswith(("Krins:", "Krets:")):
                pg, hb = _PRGJ.search(line), _HERRED.search(line)
                parish_name = parish_name or (pg.group(1).strip() if pg else "")
                muni_name = muni_name or (hb.group(1).strip() if hb else "")
                continue
            if line.startswith("Bustadnr."):
                flush()
                pending_dwelling_header = line
                cols = None
                continue
            if pending_dwelling_header is not None:
                h = pending_dwelling_header
                label = "Namn" if "Namn" in h else "Adresse"
                start = h.find(label)
                ends = [i for i in (h.find("Gnr."), h.find("Hustype")) if i > start]
                end = min(ends) if ends else start + 30
                dwelling = line[start:end].strip() if start >= 0 else ""
                pending_dwelling_header = None
                continue
            if line.startswith("Leil."):
                flush()
                cols = None
                continue
            if re.match(r"Nr\.\s+Namn", line):
                cols = _header_cols(line)
                continue
            if cols is None or _SKIP_LINE.match(line):
                continue
            p = _parse_person(line, cols, year, pageno, dwelling)
            if p:
                current.append(p)
                last = p
                seen_person = True
                continue
            # continuation of the previous person (wrapped name or birthplace)
            if last is not None:
                offset = len(line) - len(line.lstrip())
                if ":" in line:
                    pass  # a labelled note ("Heimvendt norsk-amerikanar: ..."), not a name
                elif 3 <= offset < cols.sex - 1:
                    last.name = (last.name + " " + line[offset:cols.sex].strip().replace("*", "")).strip()
                elif offset >= cols.fodested - 2 and last.birthplace:
                    last.birthplace = (last.birthplace + " " + line.strip()).strip()
    flush()

    muni_name = muni_name or parish_name
    parish_name = parish_name or muni_name
    fname = pdf.name
    url_base = f"{BOOKLET_BASE}/{year}/{county_dir}/{fname}"
    records: list[Record] = []
    seq = 0
    prev_bp = ""
    for group in groups:
        members = [Member(name=p.name, sex=p.sex, role=p.role) for p in group]
        assign_relations(members)
        _drop_inconsistent_fathers(members)
        for p, mem in zip(group, members):
            seq += 1
            given, surname = split_name(p.name)
            by, from_age = _birth_year(p.born, year)
            bp = p.birthplace
            if bp.lower() in _DITTO:
                bp = prev_bp
            bp = bp.replace("*", "").strip()
            if re.search(r"\bprgj\b|\bprgj\.", bp, re.I):
                bp = parish_name   # "born in this parish"
            prev_bp = bp
            records.append(Record(
                record_id=f"ft{year}-{muni_code}-{seq:05d}",
                source=f"Folketelling {year}, {muni_name or muni_code} (Digitalarkivet booklet {fname}, p. {p.page})",
                record_type="census", year=year, url=f"{url_base}#page={p.page}",
                given_name=given, surname=surname, farm=p.dwelling, sex=p.sex,
                birth_year=by, birthplace=bp, parish=parish_name, municipality=muni_name,
                county=county, father_name=mem.relations.get("father", ""),
                mother_name=mem.relations.get("mother", ""),
                spouse_name=mem.relations.get("spouse", ""), role=p.role,
                relations_inferred=bool(mem.relations), birth_year_from_age=from_age,
            ))
    return records
